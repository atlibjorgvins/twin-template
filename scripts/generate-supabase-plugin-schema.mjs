#!/usr/bin/env node
// Generate src/lib/data/repo/pluginSchemas.ts from the live Directus schema.
//
// The Supabase plugin tables must MATCH what the app reads and writes, and
// the source of truth for that is the Directus instance the app grew up on.
// Hand-transcribing thirty tables is how column typos are born — this script
// pulls /fields/:collection and emits idempotent CREATE TABLE fragments per
// plugin. Re-run whenever a plugin's collections change:
//
//   DIRECTUS_URL=https://your-server DIRECTUS_TOKEN=... \
//     node scripts/generate-supabase-plugin-schema.mjs
//
// Policies are NOT emitted here: schemaSync.ts applies the vault-flavor
// policies (anon for personal, authenticated for managed) at apply time, so
// one fragment serves both flavors.

const URL_ = process.env.DIRECTUS_URL;
const TOKEN = process.env.DIRECTUS_TOKEN;
if (!URL_ || !TOKEN) {
  console.error('Set DIRECTUS_URL and DIRECTUS_TOKEN.');
  process.exit(1);
}

// Which plugin needs which collections. Hand-curated: this is product
// knowledge (what breaks when the plugin opens), not schema knowledge.
const PLUGIN_COLLECTIONS = {
  // Tag chips appear on core People/Org pages too — applied with everything.
  'core-tags': ['Tag', 'Person_tag', 'organization_tag'],
  notes: ['notes', 'notes_related_to', 'notes_tag'],
  projects: ['Project', 'ProjectRole', 'Project_people', 'Project_organization'],
  events: ['Dates', 'Dates_Person', 'location'],
  grants: ['Grant', 'GrantAward', 'GrantAwardPayment'],
  calendar: ['CalendarMapping'],
  tasks: ['focus_task'],
  focus: ['focus_task', 'focus_session'],
  habits: ['habit', 'habit_entry'],
  family: ['Person_family'],
  interactions: ['Activity', 'ActivityKind', 'Activity_Person', 'Activity_organization', 'Activity_tag'],
  insights: ['Dates', 'Dates_Person', 'location', 'Activity', 'ActivityKind']
};

const TYPE_MAP = {
  integer: 'bigint',
  bigint: 'bigint',
  smallint: 'bigint',
  'character varying': 'text',
  varchar: 'text',
  text: 'text',
  uuid: 'uuid',
  boolean: 'boolean',
  numeric: 'numeric',
  real: 'double precision',
  'double precision': 'double precision',
  json: 'jsonb',
  jsonb: 'jsonb',
  date: 'date',
  time: 'time',
  'time without time zone': 'time',
  'timestamp with time zone': 'timestamptz',
  'timestamp without time zone': 'timestamptz'
};

async function fieldsOf(collection) {
  const res = await fetch(`${URL_}/fields/${collection}`, {
    headers: { Authorization: `Bearer ${TOKEN}` }
  });
  if (!res.ok) throw new Error(`${collection}: ${res.status}`);
  return (await res.json()).data;
}

// Column names that are Postgres reserved words in a column position — met
// in the wild: Dates.end. Quoted defensively; harmless when over-applied.
const RESERVED = new Set([
  'end', 'order', 'user', 'group', 'primary', 'references', 'check', 'all',
  'table', 'select', 'where', 'from', 'to', 'do', 'for', 'with', 'limit',
  'offset', 'default', 'desc', 'asc', 'grant', 'both', 'case', 'cast'
]);

function columnSql(f) {
  const s = f.schema;
  if (!s) return null; // alias fields (o2m/m2m UI) have no column
  const pg = TYPE_MAP[s.data_type] ?? 'text';
  if (s.is_primary_key) {
    if (pg === 'uuid') return `  id uuid primary key default gen_random_uuid()`;
    if (pg === 'bigint') return `  id bigint generated by default as identity primary key`;
    return `  "${f.field}" ${pg} primary key`;
  }
  const plain = /^[a-z_][a-z0-9_]*$/.test(f.field) && !RESERVED.has(f.field);
  const name = plain ? f.field : `"${f.field}"`;
  return `  ${name} ${pg}`;
}

const collections = [...new Set(Object.values(PLUGIN_COLLECTIONS).flat())];
const tableSql = {};
for (const c of collections) {
  const fields = await fieldsOf(c);
  const cols = fields.map(columnSql).filter(Boolean);
  const quoted = /[A-Z]/.test(c) ? `"${c}"` : c;
  tableSql[c] = `create table if not exists ${quoted} (\n${cols.join(',\n')}\n);`;
  console.error(`✓ ${c} (${cols.length} columns)`);
}

const fragments = Object.fromEntries(
  Object.entries(PLUGIN_COLLECTIONS).map(([plugin, cols]) => [
    plugin,
    { tables: cols, sql: cols.map((c) => tableSql[c]).join('\n\n') }
  ])
);

const out = `// GENERATED by scripts/generate-supabase-plugin-schema.mjs — do not edit
// by hand; re-run the script against the source Directus instance instead.
//
// Idempotent CREATE TABLE fragments per plugin, for provisioning a Supabase
// vault when a plugin is enabled (schemaSync.ts). Policies are applied at
// apply time in the vault's flavor, so none appear here.

export interface PluginSchema {
  /** The tables this plugin needs (policy application iterates these). */
  tables: string[];
  /** Idempotent DDL creating them. */
  sql: string;
}

export const PLUGIN_SCHEMAS: Record<string, PluginSchema> = ${JSON.stringify(fragments, null, 2)};
`;

process.stdout.write(out);
